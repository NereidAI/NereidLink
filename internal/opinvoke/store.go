// store.go persists gateway operation tasks (migration 0072).

package opinvoke

import (
	"context"
	"fmt"
	"time"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"
)

const taskColumns = `id::text, tenant_id::text, gateway_id::text, operation,
	type_version, params, result, status, reason, risk,
	invoked_by::text, invoked_by_email, started_at, finished_at`

// scanTask decodes one task row. Timestamps are rendered as RFC3339 UTC.
func scanTask(row pgx.Row) (Task, error) {
	var t Task
	var result []byte
	var finishedAt *time.Time
	err := row.Scan(&t.ID, &t.TenantID, &t.GatewayID, &t.Operation,
		&t.TypeVersion, &t.Params, &result, &t.Status, &t.Reason, &t.Risk,
		&t.InvokedBy, &t.InvokedByEmail, &startedAt{t: &t.StartedAt}, &finishedAt)
	if len(result) > 0 {
		t.Result = result
	}
	if finishedAt != nil {
		t.FinishedAt = formatUTC(*finishedAt)
	}
	return t, err
}

// startedAt scans a timestamptz into the RFC3339 string field.
type startedAt struct {
	t *string
}

// Scan implements pgx's Scanner.
func (s startedAt) Scan(v any) error {
	if v == nil {
		return nil
	}
	at, ok := v.(time.Time)
	if !ok {
		return fmt.Errorf("started_at: expected time, got %T", v)
	}
	*s.t = formatUTC(at)
	return nil
}

// Store is the PostgreSQL task store.
type Store struct {
	pool *pgxpool.Pool
}

// NewStore constructs a task store.
func NewStore(pool *pgxpool.Pool) *Store {
	return &Store{pool: pool}
}

// Insert records a new task in PENDING. The id (task UUID) is generated by
// the service so it is known before the dispatch request.
func (s *Store) Insert(ctx context.Context, t Task, startedAt time.Time) error {
	_, err := s.pool.Exec(ctx,
		`INSERT INTO gateway_operation_task
		 (id, tenant_id, gateway_id, operation, type_version, params,
		  status, risk, invoked_by, invoked_by_email, started_at)
		 VALUES ($1,$2,$3,$4,$5,$6,'PENDING',$7,$8,$9,$10)`,
		t.ID, t.TenantID, t.GatewayID, t.Operation, t.TypeVersion,
		t.Params, t.Risk, t.InvokedBy, t.InvokedByEmail, startedAt)
	if err != nil {
		return fmt.Errorf("insert operation task: %w", err)
	}
	return nil
}

// Complete stores the terminal status, result and finish time.
func (s *Store) Complete(ctx context.Context, id, status string, result []byte, reason string, finishedAt time.Time) error {
	_, err := s.pool.Exec(ctx,
		`UPDATE gateway_operation_task
		 SET status=$2, result=$3, reason=$4, finished_at=$5, updated_at=$5
		 WHERE id=$1`,
		id, status, result, reason, finishedAt)
	if err != nil {
		return fmt.Errorf("complete operation task: %w", err)
	}
	return nil
}

// Get loads one task.
func (s *Store) Get(ctx context.Context, tenantID, id string) (Task, error) {
	t, err := scanTask(s.pool.QueryRow(ctx,
		`SELECT `+taskColumns+` FROM gateway_operation_task
		 WHERE tenant_id=$1 AND id=$2`, tenantID, id))
	if err == pgx.ErrNoRows {
		return Task{}, ErrNotFound
	}
	if err != nil {
		return Task{}, fmt.Errorf("load operation task: %w", err)
	}
	return t, nil
}

// ListByGateway returns the newest tasks for one gateway.
func (s *Store) ListByGateway(ctx context.Context, tenantID, gatewayID string, limit int) ([]Task, error) {
	rows, err := s.pool.Query(ctx,
		`SELECT `+taskColumns+` FROM gateway_operation_task
		 WHERE tenant_id=$1 AND gateway_id=$2
		 ORDER BY started_at DESC
		 LIMIT $3`, tenantID, gatewayID, limit)
	if err != nil {
		return nil, fmt.Errorf("list operation tasks: %w", err)
	}
	defer rows.Close()
	return collectTasks(rows)
}

// DeleteOlderThan deletes terminal tasks whose start time is before cutoff,
// returning the removed count. PENDING rows (orphaned by a crash) are not
// touched by retention.
func (s *Store) DeleteOlderThan(ctx context.Context, cutoff time.Time) (int64, error) {
	tag, err := s.pool.Exec(ctx,
		`DELETE FROM gateway_operation_task
		 WHERE status <> 'PENDING' AND started_at < $1`, cutoff)
	if err != nil {
		return 0, fmt.Errorf("delete old operation tasks: %w", err)
	}
	return tag.RowsAffected(), nil
}

func collectTasks(rows pgx.Rows) ([]Task, error) {
	out := []Task{}
	for rows.Next() {
		t, err := scanTask(rows)
		if err != nil {
			return nil, err
		}
		out = append(out, t)
	}
	return out, rows.Err()
}
