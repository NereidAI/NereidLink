// aggregator.go implements the node side of ADR-0025 accounting: it
// publishes this node's sampled window and, on every node, consumes the
// reports of its peers into the cluster-wide store.
//
// Why both halves live in one type: publishing is trivial (one subject,
// one JSON payload) while consuming needs the queue subscription and the
// store. Keeping them together makes the subject contract — prefix,
// wildcard and queue group — defined exactly once, so a node cannot end up
// publishing a shape its peers do not parse.

package accounting

import (
	"context"
	"encoding/json"
	"fmt"
	"log/slog"
	"strings"
	"time"

	"github.com/nats-io/nats.go"
)

// SubjectPrefix is the root of the per-node accounting report subjects.
// The node id is appended, e.g. nl.accounting.n1.
const SubjectPrefix = "nl.accounting."

// SubjectWildcard matches every node report.
const SubjectWildcard = SubjectPrefix + "*"

// QueueGroup is the shared-subscription group of the accounting
// aggregators. Exactly one node in the cluster stores a given report, so
// scaling aggregators horizontally does not duplicate rows.
const QueueGroup = "nl-accounting-aggregator"

// DefaultReportInterval is the window length. It is short enough that an
// operator sees a shift within a minute, and long enough that a report is
// a meaningful sample rather than noise.
const DefaultReportInterval = 30 * time.Second

// DefaultTopN is the per-dimension candidate budget carried in a report.
const DefaultTopN = 20

// maxReportBytes bounds one inbound report. A report is generated by this
// platform, so a larger payload indicates corruption or a hostile
// publisher on the internal bus; accepting it would let one message
// exhaust the aggregator's memory.
const maxReportBytes = 1 << 20

// Reporter owns the publish side of accounting.
type Reporter struct {
	nc       *nats.Conn
	sampler  *Sampler
	interval time.Duration
	topN     int
	log      *slog.Logger
}

// NewReporter builds a Reporter.
func NewReporter(nc *nats.Conn, sampler *Sampler, log *slog.Logger) *Reporter {
	return &Reporter{
		nc:       nc,
		sampler:  sampler,
		interval: DefaultReportInterval,
		topN:     DefaultTopN,
		log:      log,
	}
}

// WithSchedule overrides the report interval and per-dimension Top-N.
func (r *Reporter) WithSchedule(interval time.Duration, topN int) *Reporter {
	if interval > 0 {
		r.interval = interval
	}
	if topN > 0 {
		r.topN = topN
	}
	return r
}

// Run publishes a report every interval until ctx is canceled.
//
// Accounting is deliberately the lowest-priority work on the node: a
// publish failure is logged and the next tick continues, because losing a
// diagnostic view must never degrade ingest. The sampler is decayed on
// every tick regardless of publish outcome so an unsubscribed bus cannot
// make a node's window grow without bound.
func (r *Reporter) Run(ctx context.Context) error {
	ticker := time.NewTicker(r.interval)
	defer ticker.Stop()
	for {
		select {
		case <-ctx.Done():
			return nil
		case now := <-ticker.C:
			r.reportOnce(ctx, now)
		}
	}
}

// reportOnce renders and publishes one window.
func (r *Reporter) reportOnce(ctx context.Context, now time.Time) {
	report := r.sampler.Snapshot(now, r.interval, r.topN)
	if report.Sampled == 0 {
		// Nothing sampled in this window: publishing zeros would only
		// inflate the hypertable and mislead a "was this node busy?"
		// question.
		return
	}
	payload, err := json.Marshal(report)
	if err != nil {
		r.log.Error("accounting report encode failed", "error", err)
		return
	}
	if err := r.nc.Publish(SubjectPrefix+r.sampler.nodeID, payload); err != nil {
		r.log.Warn("accounting report publish failed", "error", err)
	}
}

// Aggregator consumes peer reports into the store.
type Aggregator struct {
	nc    *nats.Conn
	store *Store
	log   *slog.Logger
}

// NewAggregator builds an Aggregator.
func NewAggregator(nc *nats.Conn, store *Store, log *slog.Logger) *Aggregator {
	return &Aggregator{nc: nc, store: store, log: log}
}

// Run subscribes to every node report and stores them until ctx is
// canceled.
func (a *Aggregator) Run(ctx context.Context) error {
	sub, err := a.nc.QueueSubscribe(SubjectWildcard, QueueGroup, a.handle)
	if err != nil {
		return fmt.Errorf("subscribe accounting reports: %w", err)
	}
	defer func() { _ = sub.Unsubscribe() }()

	// The subscription delivers asynchronously, so there is nothing to
	// loop over: wait for shutdown and then drain the deliveries already
	// accepted, so a report is not discarded mid-write.
	<-ctx.Done()
	if err := sub.Drain(); err != nil {
		a.log.Warn("accounting subscription drain failed", "error", err)
	}
	return nil
}

// handle decodes and stores one report. Malformed payloads are dropped
// with a log line: the bus is internal, so a bad message is a bug to fix,
// not a condition to retry forever.
func (a *Aggregator) handle(msg *nats.Msg) {
	if len(msg.Data) > maxReportBytes {
		a.log.Warn("accounting report too large; dropped",
			"bytes", len(msg.Data), "subject", msg.Subject)
		return
	}
	var report Report
	if err := json.Unmarshal(msg.Data, &report); err != nil {
		a.log.Warn("accounting report decode failed",
			"error", err, "subject", msg.Subject)
		return
	}
	if report.NodeID == "" {
		a.log.Warn("accounting report without node id; dropped",
			"subject", msg.Subject)
		return
	}
	// The subject carries the node id; trust it over the payload so one
	// node cannot attribute its traffic to another.
	if node, ok := nodeFromSubject(msg.Subject); ok {
		report.NodeID = node
	}
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	if _, err := a.store.AppendReport(ctx, report); err != nil {
		a.log.Warn("accounting report store failed",
			"node", report.NodeID, "error", err)
	}
}

// nodeFromSubject extracts the node id from nl.accounting.<node>. It
// tolerates a trailing token so a future subject layout does not silently
// mis-attribute reports.
func nodeFromSubject(subject string) (string, bool) {
	rest, ok := strings.CutPrefix(subject, SubjectPrefix)
	if !ok || rest == "" {
		return "", false
	}
	node, _, _ := strings.Cut(rest, ".")
	return node, node != ""
}
